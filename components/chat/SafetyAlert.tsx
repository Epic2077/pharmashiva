"use client";

import { AlertTriangle, CircleAlert, Info, ShieldCheck } from "lucide-react";
import type { SafetyAssessment, SafetyStatus } from "@/types/ai";
import { cn } from "@/lib/utils";

interface SafetyAlertProps {
  safety: SafetyAssessment;
}

const STATUS_CONFIG: Record<
  SafetyStatus,
  {
    label: string;
    icon: typeof AlertTriangle;
    container: string;
    header: string;
  }
> = {
  HIGH_RISK: {
    label: "Urgent safety alert",
    icon: AlertTriangle,
    container: "border-danger/30 bg-danger-background text-foreground",
    header: "text-danger",
  },
  UNRESOLVED: {
    label: "Safety information needed",
    icon: CircleAlert,
    container: "border-warning/30 bg-warning-background text-foreground",
    header: "text-warning",
  },
  LOWER_RISK: {
    label: "Safety check",
    icon: ShieldCheck,
    container: "border-success/30 bg-success-background text-foreground",
    header: "text-success",
  },
};

/**
 * Renders the authoritative safety assessment independently of the answer text,
 * using explicit labels (not colour alone) to communicate risk.
 */
export function SafetyAlert({ safety }: SafetyAlertProps) {
  const config = STATUS_CONFIG[safety.status];
  const Icon = config.icon;

  return (
    <aside
      role="alert"
      aria-live={safety.status === "HIGH_RISK" ? "assertive" : "polite"}
      className={cn(
        "my-3 overflow-hidden rounded-2xl border shadow-sm",
        config.container,
      )}
    >
      <div
        className={cn(
          "flex items-center gap-2 border-b border-current/10 px-4 py-2.5 text-sm font-semibold",
          config.header,
        )}
      >
        <Icon size={17} aria-hidden="true" />
        <span>{config.label}</span>
      </div>

      <div className="space-y-3 px-4 py-3.5 text-sm leading-6">
        <p className="font-medium text-foreground">{safety.title}</p>
        <p className="text-foreground/90">{safety.explanation}</p>

        {safety.nextSteps.length > 0 ? (
          <div>
            <p className="mb-1 text-xs font-semibold uppercase tracking-wide text-foreground/70">
              Recommended next steps
            </p>
            <ul className="list-disc space-y-1 pl-5 marker:text-current">
              {safety.nextSteps.map((step) => (
                <li key={step}>{step}</li>
              ))}
            </ul>
          </div>
        ) : null}

        {safety.questions.length > 0 ? (
          <div>
            <p className="mb-1 text-xs font-semibold uppercase tracking-wide text-foreground/70">
              Please clarify
            </p>
            <ul className="list-disc space-y-1 pl-5 marker:text-current">
              {safety.questions.map((question) => (
                <li key={question}>{question}</li>
              ))}
            </ul>
          </div>
        ) : null}

        {safety.deterministicOnly ? (
          <p className="flex items-start gap-1.5 text-xs text-muted-foreground">
            <Info size={13} className="mt-0.5 shrink-0" aria-hidden="true" />
            <span>
              Generated by deterministic safety rules only — the AI model was not
              available for this assessment.
            </span>
          </p>
        ) : null}

        {safety.status === "LOWER_RISK" ? (
          <p className="text-xs text-muted-foreground">
            No red flag was identified from the available information — this is
            not a diagnosis.
          </p>
        ) : null}
      </div>
    </aside>
  );
}
